// 2026-07-23  F1 + F2  (reports/results/ATTN_F1F2_SOFTMAX_SHARPNESS.md,
//                       reports/results/CTXN_ATTN_NUMERICS_RCA.md)
// ---------------------------------------------------------------------
// THE TABLE IS NOT exp(x).  IT IS exp(x/sqrt(2)).  DO NOT "FIX" THAT, AND DO NOT
// ALSO CHANGE SCORE_NORM_SHR — that would double-correct.
//
// F1 — the softmax temperature shipped sqrt(2) TOO SHARP.
//   attention_head_assembly*_perbank*.sv computes
//       score_norm = score_out >>> SCORE_NORM_SHR,  SCORE_NORM_SHR = 11
//                                                   (eagle4_drafter.sv:2871)
//   score_out is the Q(2*G5_FRAC=20) raw Q.K dot, so score_norm is Q4.12 of
//   (dot / 2^9) = dot/8.  The reference (reference/src/attn.cpp:73) wants
//   dot / sqrt(D_HEAD=128) = dot/11.3137.  The exact shift is 11.5 — a HALF BIT
//   an integer `>>>` cannot express — so every exponent was sqrt(2) too big and
//   the distribution 1.414x too peaked (78% of the ctx>=2 attention-weight error).
//
//   FIX — chosen over the prescribed `(score_out * 32'sd11585) >>> 25` in the
//   assembly: the 1/sqrt(2) is folded into the TABLE VALUES,
//       EXP_PWL_LUT[i] = round(4096 * exp(-(i*2^IDX_SHIFT / 2^12) / sqrt(2)))
//   Equivalent because softmax is invariant to WHERE a positive scalar multiplies
//   the exponent, and BOTH the numerator and the denominator are produced by this
//   one table (softmax_exp_sum.sv:46,61).  It costs ZERO multipliers (the assembly
//   variant would be one 32x15 multiply per engine, 6 at HEAD_PAR=6, sitting on
//   the score->max_tracker path), and it leaves `score_norm`, score_max_tracker,
//   score_buf and the max compare BIT-IDENTICAL — the max is monotone in either
//   scale, so argmax and delta ordering are unchanged.
//
// F1b — grid.  Folding also frees the index step, so IDX_SHIFT went 10 -> 7:
//   the TRUE-exponent step is now 2^7/2^12/sqrt(2) = 0.0221 instead of 0.1768.
//   (The assembly-multiply variant would have made it COARSER, 0.25.)  Measured
//   L1 weight error vs fp32 attn.cpp at ctx=4:
//       0.1607 shipped  ->  0.0369 prescribed multiply  ->  0.0033 here
//   (exact-exp floor, set by inv_q12 + the >>>12 output truncation, is 0.00065).
//
// F2 — the old `default: 32'd1` floored EVERY far tail at 1/4096 instead of 0.
//   Those invented weights inflated the softmax DENOMINATOR while truncating to 0
//   in the numerator (attn = exp*inv >>> 12) => pure head-GAIN droop
//   4096/(4096+ctx-1) = 0.842 @ctx=767, 0.800 @ctx=1024.  The table now runs out
//   to the LAST index whose true weight is still a nonzero Q4.12 code (index 407,
//   true exponent -8.99, weight 1.24e-4); everything beyond is exactly 0.
//
//   DIVIDE-BY-ZERO SAFETY (the softmax sum can never become 0):
//     - the max position always streams through softmax_exp_sum with
//       delta = score - max = 0, which takes the `delta_q12 >= 0` early-out and
//       returns 4096 => sum_so_far >= 4096 for any ctx_len >= 1; and
//     - inv_q12.sv:76-79 independently returns the saturated 32767 when
//       sum_q12 <= 0, so even a hypothetical zero sum cannot divide by zero.
//
// ctx=1 INERTNESS: at ctx_len=1 the only position IS the max, delta == 0, so the
//   early-out returns 4096 exactly as before => the depth-0 seal (frontier 8/8,
//   G5 0xc59befef / G7p 0xd8d6d147 / G8RESC 0x002c953c) is byte-identical BY
//   CONSTRUCTION — neither F1 nor F2 can be observed at ctx=1.
//
// The LUT block below is AUTO-GENERATED by scripts/gen_exp_pwl_lut.py — a constant
// localparam array, NOT $readmemh, so it is immune to the [Synth 8-3848] no-driver
// bake-drop (same discipline as tree_pow2_lut.svh).
// =====================================================================

